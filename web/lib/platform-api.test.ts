describe("same-origin proxy for platform routes", () => {
  it("forwards the platform prefixes and still refuses unknown roots", async () => {
    const { NextRequest } = await import("next/server");
    const { GET } = await import("../app/api/backend/[...path]/route");
    const forwarded: string[] = [];
    globalThis.fetch = ((input: RequestInfo | URL) => {
      forwarded.push(String(input));
      return Promise.resolve(Response.json({ items: [], total: 0 }));
    }) as typeof fetch;
    for (const root of ["signals", "markets", "requests", "priorities", "market-data", "runs", "agents", "capabilities", "tasks", "threads"]) {
      const response = await GET(new NextRequest(`http://localhost:3000/api/backend/${root}`), {
        params: Promise.resolve({ path: [root] }),
      });
      expect(response.status).toBe(200);
    }
    expect(forwarded).toHaveLength(10);
    const refused = await GET(new NextRequest("http://localhost:3000/api/backend/admin"), {
      params: Promise.resolve({ path: ["admin"] }),
    });
    expect(refused.status).toBe(404);
  });
});
