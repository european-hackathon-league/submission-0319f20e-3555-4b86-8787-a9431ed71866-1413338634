/** The server's route catalogue, read once. Endpoints missing from it are never called. */
export function useApiCatalog() {
  return useQuery({
    queryKey: ["openapi-paths"],
    queryFn: ({ signal }) => api<unknown>("/openapi.json", { signal }).then(toApiPaths),
    staleTime: Infinity,
    retry: false,
  });
}
/** true / false once the catalogue is known; true when it cannot be read (the request then decides). */
export function useEndpointAvailable(endpoint: EndpointName): boolean | undefined {
  const catalog = useApiCatalog();
  if (catalog.isError) return true;
  return catalog.data ? catalog.data.has(ENDPOINTS[endpoint]) : undefined;
}
export function usePlatformQuery<T>(
  endpoint: EndpointName,
  options: { queryKey: QueryKey; queryFn: (context: { signal: AbortSignal }) => Promise<T>; enabled?: boolean; staleTime?: number },
) {
  const declared = useEndpointAvailable(endpoint);
  const query = useQuery({
    queryKey: options.queryKey,
    queryFn: ({ signal }) => options.queryFn({ signal }),
    enabled: declared === true && (options.enabled ?? true),
    staleTime: options.staleTime,
    retry: (count, error) => !(error instanceof ApiError && error.status < 500) && count < 1,
  });
  return { endpoint, query, unavailable: declared === false || isUnavailable(query.error), checking: declared === undefined };
}
export type PlatformState<T> = ReturnType<typeof usePlatformQuery<T>>;

export function Unavailable({ endpoint, compact }: { endpoint: EndpointName; compact?: boolean }) {
  return (
    <div className={`platform-unavailable ${compact ? "is-compact" : ""}`} role="status">
      <PlugZap size={compact ? 15 : 22} />
      <div>
        <strong>Not available on this server</strong>
        <span>
          <code>{ENDPOINTS[endpoint]}</code> is unavailable on this server.
        </span>
      </div>
    </div>
  );
}
/** Loading, unavailable, error and empty states for one platform read; children render only real data. */
export function PlatformView<T>({
  state,
  empty,
  isEmpty,
  compact,
  children,
}: {
  state: PlatformState<T>;
  empty?: React.ReactNode;
  isEmpty?: (data: T) => boolean;
  compact?: boolean;
  children: (data: T) => React.ReactNode;
}) {
  const { query, unavailable, checking, endpoint } = state;
  if (unavailable) return <Unavailable endpoint={endpoint} compact={compact} />;
  if (query.error) return <ErrorMessage error={query.error} retry={() => void query.refetch()} />;
  if (checking || (query.isFetching && query.isPending)) return <Loading />;
  if (query.data === undefined) return null;
  if (isEmpty?.(query.data)) return <>{empty}</>;
  return <>{children(query.data)}</>;
}

