/** Factor values on their recorded 0–5 scale with the recorded weight; contributions only when the server sent them. */
export function FactorBars({ factors, compact }: { factors: FactorView[]; compact?: boolean }) {
  if (!factors.length) return <span className="muted text-xs">No factor breakdown recorded.</span>;
  return (
    <div className={`factor-bars ${compact ? "is-compact" : ""}`}>
      {factors.map((factor) => (
        <div key={factor.name} className={`factor-bar ${factor.notMeasured ? "not-measured" : ""}`}>
          <span className="factor-name">{readable(factor.name)}</span>
          <span className="factor-track" aria-hidden>
            <span style={{ width: `${Math.max(0, Math.min(100, ((factor.value ?? 0) / 5) * 100))}%` }} />
          </span>
          <span className="factor-value tabular-nums">
            {factor.value === null ? "–" : factor.value.toFixed(1)}
            {!compact && factor.weight !== null && <small> × {factor.weight.toFixed(2)}</small>}
          </span>
          {factor.notMeasured && <span className="not-measured-flag">Not measured</span>}
          {!compact && !!factor.notes.length && <small className="factor-notes">{factor.notes.join(" · ")}</small>}
        </div>
      ))}
    </div>
  );
}

export function sourceHref(base: string, ref: SourceRef, market?: string | null) {
  const scoped = market ? base.replace(/\/[^/]+$/, `/${market.toLowerCase()}`) : base;
  const id = encodeURIComponent(ref.id);
  switch (ref.type) {
    case "evidence":
      return `${scoped}/evidence?evidence=${id}`;
    case "finding":
      return `${scoped}/evidence?mode=findings&q=${id}`;
    case "requirement":
      return `${scoped}/requirements?requirement=${id}`;
    case "request":
      return `${base}/requests?request=${id}`;
    case "conflict":
    case "market_conflict":
      return `${base}/markets?conflict=${id}`;
    case "signal_item":
      return `${scoped}/signals?item=${id}`;
    case "run":
      return `${base}/audit?entity=${id}`;
    default:
      return null;
  }
}
export function SourceLinks({ refs, market, max = 8 }: { refs: SourceRef[]; market?: string | null; max?: number }) {
  const { base } = useWorkspace();
  const [all, setAll] = useState(false);
  if (!refs.length) return <span className="muted text-xs">No source ids recorded.</span>;
  const shown = all ? refs : refs.slice(0, max);
  return (
    <span className="source-links">
      {shown.map((ref) => {
        const href = sourceHref(base, ref, market);
        const label = `${readable(ref.type)} ${shortId(ref.id)}`;
        return href ? (
          <Link key={`${ref.type}:${ref.id}`} href={href} className="source-chip" title={ref.id}>
            {label}
          </Link>
        ) : (
          <span key={`${ref.type}:${ref.id}`} className="source-chip is-plain" title={ref.id}>
            {label}
          </span>
        );
      })}
      {refs.length > max && (
        <button type="button" className="source-chip is-plain" aria-expanded={all} onClick={() => setAll(!all)}>
          {all ? "Show fewer" : `+${refs.length - max} more`}
        </button>
      )}
    </span>
  );
}
/** Runs an A0/A1 capability as the selected human reviewer; results and failures are announced. */
export function useCapability(endpoint: EndpointName, fn: (actorId: string) => Promise<unknown>, invalidate: QueryKey[]) {
  const { actor } = useWorkspace();
  const client = useQueryClient();
  const available = useEndpointAvailable(endpoint);
  const mutation = useMutation({
    mutationFn: () => {
      if (!actor) throw new Error("Select a reviewer first.");
      return fn(actor.id);
    },
    onSuccess: (value) => {
      toast.success(describeWrite(value));
      for (const key of invalidate) void client.invalidateQueries({ queryKey: key });
    },
    onError: (error) => toast.error(gateError(error).message),
  });
  const reason =
    available === false
      ? `Not available on this server (${ENDPOINTS[endpoint]})`
      : !actor
        ? "Select a reviewer first"
        : !canAct(actor, "run")
          ? "Requires an active human reviewer"
          : null;
  return { mutation, reason, available };
}
export function CapabilityButton({
  capability,
  children,
  variant = "outline",
}: {
  capability: ReturnType<typeof useCapability>;
  children: React.ReactNode;
  variant?: "outline" | "default" | "ghost";
}) {
  const { mutation, reason } = capability;
  return (
    <Button
      type="button"
      variant={variant}
      size="sm"
      disabled={!!reason || mutation.isPending}
      title={reason ?? undefined}
      onClick={() => mutation.mutate()}
    >
      {children}
      {mutation.isPending && "…"}
    </Button>
  );
}

/**
 * A human decision gate: requires a declared, active human actor with the PM role (or the role the
 * action needs) and a written rationale. The API and a database trigger enforce the same rule; a 403
 * from the server is shown as a refusal, never retried.
 */
export function GateDialog({
  open,
  onOpenChange,
  title,
  description,
  submitLabel,
  role = "approve",
  pending,
  error,
  ready = true,
  onSubmit,
  children,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  title: string;
  description: string;
  submitLabel: string;
  role?: "approve" | "run" | "score";
  pending: boolean;
  error: unknown;
  ready?: boolean;
  onSubmit: (actorId: string, rationale: string) => void;
  children?: React.ReactNode;
}) {
  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="edit-dialog">
        <DialogTitle>{title}</DialogTitle>
        <DialogDescription>{description}</DialogDescription>
        {open && (
          <GateForm submitLabel={submitLabel} role={role} pending={pending} error={error} ready={ready} onSubmit={onSubmit}>
            {children}
          </GateForm>
        )}
      </DialogContent>
    </Dialog>
  );
}
function GateForm({
  submitLabel,
  role,
  pending,
  error,
  ready,
  onSubmit,
  children,
}: {
  submitLabel: string;
  role: "approve" | "run" | "score";
  pending: boolean;
  error: unknown;
  ready: boolean;
  onSubmit: (actorId: string, rationale: string) => void;
  children?: React.ReactNode;
}) {
  const { actor, actors, setActor } = useWorkspace();
  const [rationale, setRationale] = useState("");
  const allowed = canAct(actor, role);
  const roleText = role === "score" ? "a lead PM" : role === "approve" ? "a PM or lead PM" : "an active human reviewer";
  return (
    <form
      className="pm-form"
      onSubmit={(event) => {
        event.preventDefault();
        if (actor && allowed && rationale.trim() && ready) onSubmit(actor.id, rationale.trim());
      }}
    >
      {children}
      <Field label="Deciding human actor">
        <PmSelect
          aria-label="Deciding human actor"
          value={actor?.id || ""}
          onValueChange={setActor}
          disabled={pending}
          options={[
            { value: "", label: "Select a human reviewer" },
            ...actors.map((person) => ({ value: person.id, label: `${person.display_name} · ${readable(person.role)} · ${person.id}` })),
          ]}
        />
      </Field>
      {actor && !allowed && (
        <p className="muted text-xs" role="status">
          {actor.display_name} cannot take this decision; it needs {roleText}.
        </p>
      )}
      <Field label="Rationale (recorded in the audit trail)">
        <textarea
          className="pm-input"
          rows={3}
          required
          maxLength={2000}
          value={rationale}
          disabled={pending}
          onChange={(event) => setRationale(event.target.value)}
          placeholder="Explain the decision and how you weighed the evidence."
        />
      </Field>
      <div className="gate-footer">
        <span className="muted text-xs">
          <ShieldCheck size={13} /> A person must confirm this action.
        </span>
        <Button type="submit" disabled={!actor || !allowed || !rationale.trim() || !ready || pending}>
          {pending ? "Recording…" : submitLabel}
        </Button>
      </div>
      {!!error && <ErrorMessage error={gateError(error)} />}
    </form>
  );
}
